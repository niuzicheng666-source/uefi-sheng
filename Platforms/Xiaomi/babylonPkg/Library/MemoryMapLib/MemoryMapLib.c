// babylon (Xiaomi MIX Fold 3, SM8550) memory map.
//
// Two disjoint sets, tiled so that no descriptor overlaps another:
//  * babylon reservations from the live /sys/firmware/fdt reserved-memory nodes,
//    plus the SoC firmware carveouts sheng proved on the same SM8550;
//  * the UEFI window (FD at 0xA7100000 + 0x300000, heaps, stack) copied verbatim
//    from shengPkg, whose values match [uefi_fd] of uefi-sheng and the BootShim
//    header of the boot image;
//  * DRAM gaps computed as the 16 GB banks minus every claimed range, so the
//    memory manager never gets a range another descriptor owns.
//
// The reserved nodes that collide with the UEFI window (ramoops at 0xA7000000
// spans FD Reserved and the UEFI FD itself) are intentionally absent: declaring
// them reserved makes SEC abort while it executes from the FD.
